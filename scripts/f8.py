def set_cells(tid, rows, start_row=1):
    cells = []
    for i, rowdata in enumerate(rows):
        for c, v in enumerate(rowdata, start=1):
            cells.append({'row': start_row + i, 'col': c, 'text': v})
    r = call('doc_set_table_cells', {'table_id': tid, 'cells': cells})
    return 'ok' in r


def ins_rows(tid, anchor, count, below=True):
    r = call('doc_insert_table_rows', {'table_id': tid,
            'row_inserts': [{'anchor_row': anchor, 'insert_below': below, 'count': count}]})
    return 'ok' in r


